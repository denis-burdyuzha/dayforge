/**
 * Builds WolfL{N}AssetData.ts from src/assets/images/baseForm/warrior/wolfL{N}.svg (source SVGs are read only).
 *
 * - Polygons are taken in document order (= z-order of the SVG), with their own fill (no palette remap —
 *   same as the fox: the asset colours are rendered as is).
 * - No zones (the wolf is not zone-annotated).
 * - Canvas fit = the fox rule: the polygon bbox is contained in the 168 × 208 box (16px margin of the
 *   200 × 240 avatar canvas) and centred on (100, 120). Written as WOLF_L{N}_FIT { scale, tx, ty }.
 *
 * Usage: node scripts/buildWolfAssets.mjs
 */
import fs from "node:fs";
import path from "node:path";

const SRC_DIR = "src/assets/images/baseForm/warrior";
const OUT_DIR = "src/entities/character/ui/ModularAvatar/creatures/wolf/assets";
const CANVAS = { w: 200, h: 240, margin: 16 };

fs.mkdirSync(OUT_DIR, { recursive: true });

for (const n of [1, 2, 3, 4, 5]) {
  const svg = fs.readFileSync(path.join(SRC_DIR, `wolfL${n}.svg`), "utf8");
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1] ?? "";
  const polys = [...svg.matchAll(/<polygon\b([^>]*)>/g)].map((m) => {
    const attr = (name) => new RegExp(`\\b${name}="([^"]+)"`).exec(m[1])?.[1];
    const id = attr("id");
    const points = attr("points");
    const fill = attr("fill");
    if (!id || !points || !fill) throw new Error(`wolfL${n}: polygon without id/points/fill: ${m[0]}`);
    return { id, points: points.trim(), defaultFill: fill.toLowerCase() };
  });
  if (new Set(polys.map((p) => p.id)).size !== polys.length) throw new Error(`wolfL${n}: duplicate ids`);

  let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity;
  for (const p of polys)
    for (const pair of p.points.split(/\s+/)) {
      const [x, y] = pair.split(",").map(Number);
      x0 = Math.min(x0, x); y0 = Math.min(y0, y); x1 = Math.max(x1, x); y1 = Math.max(y1, y);
    }
  const boxW = CANVAS.w - 2 * CANVAS.margin;
  const boxH = CANVAS.h - 2 * CANVAS.margin;
  const scale = Math.min(boxW / (x1 - x0), boxH / (y1 - y0));
  const tx = CANVAS.w / 2 - ((x0 + x1) / 2) * scale;
  const ty = CANVAS.h / 2 - ((y0 + y1) / 2) * scale;
  const r = (v) => Math.round(v * 10000) / 10000;

  const out =
    `/* Generated by scripts/buildWolfAssets.mjs from ${SRC_DIR}/wolfL${n}.svg — do not edit by hand. */\n\n` +
    `export interface WolfPolygonDef {\n  id: string;\n  points: string;\n  defaultFill: string;\n}\n\n` +
    `/** Source viewBox ${viewBox}; polygon bbox ${x0},${y0} – ${x1},${y1} */\n` +
    `export const WOLF_L${n}_FIT = { scale: ${r(scale)}, tx: ${r(tx)}, ty: ${r(ty)}, viewBox: "${viewBox}" } as const;\n\n` +
    `export const WOLF_L${n}_POLYGONS: WolfPolygonDef[] = ${JSON.stringify(polys, null, 2)};\n`;
  fs.writeFileSync(path.join(OUT_DIR, `WolfL${n}AssetData.ts`), out);
  console.log(`L${n}: ${polys.length} polygons, viewBox ${viewBox}, fit scale ${r(scale)} tx ${r(tx)} ty ${r(ty)}`);
}
